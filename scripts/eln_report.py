#!/usr/bin/python3 -I
"""Per-package report of the ELN packages for
https://github.com/fedora-eln/eln/issues/610.

Usage: eln_report.py INVENTORY PRS OUT.md

INVENTORY  today's inventory (classify.py output)
PRS        the PR list written by progress.py --prs

Uses data/eln-in-scope.txt and data/state/packages.jsonl; nothing is fetched.
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import progress  # noqa: E402
import state  # noqa: E402

BUG = 'https://bugzilla.redhat.com/show_bug.cgi?id=%s'
PROPOSALS = 'https://github.com/Jakuje/openpgpverify-migration/tree/main/proposals/%s/'
REASON = {
    'weak-key': 'DSA-1024 key',
    'sha1-cert': 'SHA-1 self-signatures on the key',
    'sha1-sig-and-cert': 'SHA-1 self-signatures on the key',
    'v3-key-sha1-cert': 'SHA-1 self-signatures on the key',
}


def main():
    inv, prs_path, out = sys.argv[1:4]
    today = progress.load(inv)
    date = os.path.basename(inv)[len('inventory-'):-len('.jsonl')]
    st = state.load()
    prs = collections.defaultdict(list)
    for line in list(open(prs_path))[1:]:
        r = dict(zip(('package', 'id', 'status', 'author', 'url', 'title', 'updated'),
                     line.rstrip('\n').split('\t')))
        prs[r['package']].append(r)
    eln = sorted(open(os.path.join(state.ROOT, 'data', 'eln-in-scope.txt')).read().split())

    groups = collections.defaultdict(list)
    for p in eln:
        t = today.get(p)
        cat = t['category'] if t else None
        rec = st.get(p) or {}
        by = {r['status']: r for r in prs[p]}
        if cat == 'converted':
            groups['converted'].append((p, 'PR [#%s](%s)' % (by['Merged']['id'], by['Merged']['url'])
                                        if 'Merged' in by else 'by the maintainer'))
        elif t is None:
            groups['retired'].append((p, ''))
        elif cat not in progress.IN_SCOPE:
            groups['dropped'].append((p, 'no signature check left in the spec'))
        elif 'Merged' in by:
            groups['converted'].append((p, 'PR [#%s](%s), merged after the snapshot'
                                        % (by['Merged']['id'], by['Merged']['url'])))
        elif 'Open' in by:
            o = by['Open']
            groups['open'].append((p, '[#%s](%s) by %s, last updated %s' % (
                o['id'], o['url'], o['author'], o['updated'])))
        elif rec.get('bug_id'):
            groups['bug'].append((p, '[rhbz#%s](%s): %s' % (
                rec['bug_id'], BUG % rec['bug_id'],
                REASON.get(rec.get('bug_reason'), rec.get('bug_reason') or 'see the bug'))))
        elif rec.get('status') == 'tested':
            groups['ready'].append((p, '[patches and PR text](%s)' % (PROPOSALS % p)))
        else:
            groups['other'].append((p, rec.get('outcome_detail') or rec.get('status') or ''))

    n = {k: len(v) for k, v in groups.items()}
    L = ['# ELN packages: source signature verification',
         '',
         'State as of %s, for [eln#610](https://github.com/fedora-eln/eln/issues/610). '
         'The %d packages are the ones in the ELN buildroot that verified upstream sources '
         'with `%%gpgverify` or GnuPG on 2026-10-06. Generated by `scripts/eln_report.py`.'
         % (date, len(eln)),
         '',
         '| | Packages |', '|---|---|']
    names = [('converted', 'Converted to `%openpgpverify` in rawhide'),
             ('open', 'PR open, waiting for the maintainer'),
             ('ready', 'PR prepared, not opened yet'),
             ('bug', 'Blocked on the upstream key (bug filed)'),
             ('other', 'Other'),
             ('dropped', 'Signature check dropped by the maintainer'),
             ('retired', 'Retired')]
    L += ['| %s | %d |' % (t, n[k]) for k, t in names if n.get(k)]

    def table(k, title, intro, col):
        if not groups.get(k):
            return
        L.extend(['', '## %s (%d)' % (title, n[k]), ''])
        if intro:
            L.extend([intro, ''])
        L.extend(['| Package | %s |' % col, '|---|---|'])
        L.extend('| %s | %s |' % (p, d) for p, d in groups[k])

    table('bug', 'Blocked on the upstream key',
          'No key that sqv accepts is published. Each bug explains the problem and the '
          'options (a new or re-signed key upstream, or a decision by the maintainer). '
          'The bugs are tracked in [rhbz#2569052](%s).' % (BUG % 2569052), 'Bug')
    table('ready', 'PR prepared, not opened yet',
          'Tested in mock; the patches and the PR text are ready.', 'Proposal')
    table('open', 'PR open', None, 'PR')
    table('other', 'Other', None, 'Note')
    table('dropped', 'Signature check dropped', None, 'Note')
    table('converted', 'Converted', None, 'How')
    open(out, 'w').write('\n'.join(L) + '\n')
    print(', '.join('%s %d' % kv for kv in n.items()))


if __name__ == '__main__':
    main()
